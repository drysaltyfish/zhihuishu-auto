import fs from 'node:fs';
const u = new URL(fs.readFileSync('data/server.url','utf8').trim());
const t = u.searchParams.get('t');
const api = (p, body) => fetch('http://127.0.0.1:8731'+p+'?t='+t, body?{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body)}:{}).then(async r=>({s:r.status,b:await r.json()}));
const st = async () => (await api('/api/state')).b;
const sleep = (ms)=>new Promise(r=>setTimeout(r,ms));
const waitPhase = async (want, ms) => { const t0=Date.now(); while(Date.now()-t0<ms){ const a=await st(); if (a.phase===want) return a; await sleep(1500);} return await st(); };
console.log('quit1', (await api('/api/control',{action:'quit'})).s);
const s1 = await waitPhase('STOPPED', 40000); console.log('after quit1:', s1.phase);
console.log('start2', (await api('/api/start',{})).s);
const s2 = await waitPhase('PLAYING', 90000);
console.log('after start2:', s2.phase, '| notice=', JSON.stringify(s2.notice), '| verifyHint=', JSON.stringify(s2.verifyHint));
await sleep(5000);
const s3 = await st();
console.log('5s later:', s3.phase, '| notice=', JSON.stringify(s3.notice));
const lines = fs.readFileSync('data/runtime.log','utf8').trim().split('\n');
const bad = lines.filter(l => l.includes('异常退出'));
console.log('异常退出 行数（本次重启后）:', bad.length, bad.slice(-3).join(' / '));
console.log(lines.slice(-8).join('\n'));