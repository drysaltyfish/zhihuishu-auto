import { chromium } from 'playwright';
import fs from 'node:fs';
const url = fs.readFileSync('data/server.url', 'utf8').trim();
const br = await chromium.launch({ headless: true, channel: 'chrome' });
const pg = await br.newPage({ viewport: { width: 1440, height: 900 } });
await pg.goto(url, { waitUntil: 'networkidle' });
await new Promise(r => setTimeout(r, 1500));
const t = await pg.locator('.wrap').innerText();
console.log(t.split('\n').slice(0, 8).join(' | '));
console.log('HAS_START:', t.includes('开始听课'));
await pg.screenshot({ path: 'docs/ui-start.png', fullPage: true });
await br.close();
